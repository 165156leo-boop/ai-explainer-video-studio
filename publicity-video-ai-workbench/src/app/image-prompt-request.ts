import type { ImagePromptBrief } from "./image-prompt.ts";

/**
 * 画面词润色：发给文本模型的请求体。
 *
 * ## 这个文件回答的问题是「哪些字段该发、哪些不该发，依据是什么」
 *
 * 2026-09-18 用户连问两次，第二次把要求说透了：
 * 「你看你前面很多要发的都不是一些具体的东西，你有的可能会产生一些歧义……
 *   你在服务端的时候会自动附加的，所以不用复述。你为什么新版还要发，
 *   你要先自己判断要不要发过去。」
 *
 * 第一次我们犯的错是**收窄**（只发 5 个字段，把台词、连续性、参考图说明全扣在
 * 服务端，模型只能靠猜填空，猜出来的就是用户说的「自己的想法」）；第二次改成了
 * **全发 9 个**——那是从一个极端走到另一个极端，没有逐字段判断。现在按一条标准重判：
 *
 * > **只发「画面事实」：模型不看到就写不出来的东西。**
 * > 凡是「管道机制」（程序会确定性附加的约束、素材上传状态、拼装开关），
 * > 一律不发——发给它只有两个后果：模型照着复述一遍，或者据此发明一句建议。
 *
 * 逐字段判断结果与依据（真实数据实测，出处见括号）：
 *
 * | 字段 | 判定 | 依据 |
 * |---|---|---|
 * | `scene` | 发 | 画面的舞台，模型必须知道 |
 * | `dialogue` | 发 | 「谁对谁说什么」决定表情与语气；也是唯一能推出对话对象的来源 |
 * | `actions` | 发 | 可见动作链，画面的主干 |
 * | `continuity` | **有画面事实才发** | 见下 `imagePromptContinuityFact` |
 * | `title` | **不发** | 值形如「接待事项要真实」「案例一」——主题标语，不是画面事实。同一案例多镜共用同一标题（实测 3/6 镜完全重复），零信息量，且「主题式」表述正是模型写评价语（「信息突出」「重点明确」）的诱因 |
 * | `characters` | **不发** | 它的实际值就是 `speaker`，而 `speaker` 已被证明不可靠：`小李 → 小李`（漏掉真正的对话对象刘老师）、`无人物对白`（一句话）、`某教职工和其亲属的电话场景 → 场景切换为…人员变更为小王`（整段制作说明）、`B` / `C` / `A`（单字母）。说话人完全可以从 `dialogue` 的「名字：“台词”」前缀确定性推出，不需要这个字段 |
 * | `rules`（原 `constraintsToAppend`） | **不发** | 命中规则转出来的就是 `promptRuleInstruction` 里那句固定的绑定文案（「小陈的外观严格沿用上传的审计员A人物参考图，包括眼镜、发型、脸型和服装…」），而这句话**服务端重装时本来就会逐字追加**。发过去 = 让模型复述一遍管道内部动作，还会把「生成时使用素材库中的…」这种它无法执行的操作说明喂给它 |
 * | `referenceAssets`（原 `referenceImages`） | **不发** | 值是「已上传“审计员 A · 固定人物形象”，用于锁定审计员A的人物外观」——这是**提交准备状态**，不是画面内容；参考图本身随请求上传，画风句与人物绑定句也由服务端追加。改成在系统提示词里写死一条写作规则：不要描写人物外貌细节 |
 * | `fallbackPrompt` | 不发 | 程序自己拼的模板成品，发了它只会照抄模板 |
 * | `styleAnchored` | 不发 | 布尔拼装开关，对模型理解画面零信息量 |
 *
 * 结果是：**固定发 4 个（id / scene / dialogue / actions），连续性带画面事实时发第 5 个。**
 *
 * 撤掉 `characters` 之后必须补一件事：系统提示词要告诉模型
 * **被对话的人往往只出现在台词的称呼语里**（「刘老师，您提交的公务接待费用…」），
 * 否则「对着空座位说话」会回来——那是这个字段原本唯一真正承担的信息。
 */

